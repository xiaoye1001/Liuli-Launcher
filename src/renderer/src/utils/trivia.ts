/** 当天的冷知识（同一天总是同一条）；except 用来点「换一条」时不重复 */
export function pickTrivia(now = new Date(), except = ''): string {
  if (except) {
    const others = TRIVIA.filter((t) => t !== except)
    return others[Math.floor(Math.random() * others.length)]
  }
  const day = Math.floor(new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime() / 86_400_000)
  return TRIVIA[((day % TRIVIA.length) + TRIVIA.length) % TRIVIA.length]
}
