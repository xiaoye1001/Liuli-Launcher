const LATE_NIGHT = ['夜深了，该睡觉了', '再不睡，幻翼就要来了', '熬夜伤身，存档明天也在']

/** 选一句标语；except 用来点击换一句时不重复 */
export function pickSplash(now = new Date(), except = ''): string {
  const pick = (list: string[]): string => {
    const choices = list.length > 1 ? list.filter((line) => line !== except) : list
    return choices[Math.floor(Math.random() * choices.length)]
  }
  const holiday = HOLIDAYS[`${now.getMonth() + 1}-${now.getDate()}`]
  // 节日第一次显示节日的话，点击后换成普通的
  if (holiday && except === '') return holiday
  if (now.getHours() < 5 && Math.random() < 0.5) return pick(LATE_NIGHT)
  return pick(LINES)
}
